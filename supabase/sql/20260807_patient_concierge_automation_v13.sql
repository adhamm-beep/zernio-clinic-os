create table if not exists public.patient_appointment_requests (
  id bigint generated by default as identity primary key,
  clinic_id bigint not null references public.clinics(id) on delete restrict,
  branch_id bigint not null references public.branches(id) on delete restrict,
  customer_id bigint not null references public.customers(id) on delete cascade,
  appointment_id bigint not null references public.appointments(id) on delete cascade,
  request_type text not null check(request_type in('reschedule','cancel','check_in','add_to_calendar')),
  preferred_at timestamptz,
  reason text,
  status text not null default 'pending' check(status in('pending','reviewing','approved','declined','completed')),
  handled_by bigint references public.staff(id) on delete set null,
  handled_at timestamptz,
  created_at timestamptz not null default now()
);
create unique index if not exists patient_open_appointment_request_unique on public.patient_appointment_requests(appointment_id,request_type) where status in('pending','reviewing');

create table if not exists public.patient_consents (
  id bigint generated by default as identity primary key,
  clinic_id bigint not null references public.clinics(id) on delete restrict,
  customer_id bigint not null references public.customers(id) on delete cascade,
  appointment_id bigint references public.appointments(id) on delete cascade,
  consent_type text not null,
  title text not null,
  body text not null,
  version text not null default '1',
  status text not null default 'pending' check(status in('pending','accepted','declined','expired')),
  accepted_name text,
  accepted_at timestamptz,
  created_at timestamptz not null default now(),
  unique(customer_id,appointment_id,consent_type,version)
);

create table if not exists public.patient_messages (
  id bigint generated by default as identity primary key,
  clinic_id bigint not null references public.clinics(id) on delete restrict,
  branch_id bigint references public.branches(id) on delete restrict,
  customer_id bigint not null references public.customers(id) on delete cascade,
  appointment_id bigint references public.appointments(id) on delete set null,
  sender_type text not null check(sender_type in('patient','staff','system','ai_draft')),
  sender_staff_id bigint references public.staff(id) on delete set null,
  message text not null check(length(trim(message)) between 1 and 2000),
  category text not null default 'general' check(category in('general','booking','payment','aftercare','medical','complaint')),
  requires_reply boolean not null default false,
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists patient_messages_customer_idx on public.patient_messages(customer_id,created_at desc);

create table if not exists public.patient_packages (
  id bigint generated by default as identity primary key,
  clinic_id bigint not null references public.clinics(id) on delete restrict,
  customer_id bigint not null references public.customers(id) on delete cascade,
  service_id bigint references public.services(id) on delete set null,
  package_name text not null,
  total_sessions integer not null check(total_sessions>0),
  used_sessions integer not null default 0 check(used_sessions>=0 and used_sessions<=total_sessions),
  amount_paid numeric not null default 0 check(amount_paid>=0),
  status text not null default 'active' check(status in('active','completed','expired','cancelled')),
  starts_at date not null default current_date,
  expires_at date,
  created_at timestamptz not null default now()
);

create table if not exists public.patient_push_tokens (
  id bigint generated by default as identity primary key,
  auth_user_id uuid not null references auth.users(id) on delete cascade,
  customer_id bigint not null references public.customers(id) on delete cascade,
  expo_push_token text not null unique,
  platform text check(platform in('ios','android','web')),
  is_active boolean not null default true,
  last_seen_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create table if not exists public.patient_automation_suggestions (
  id bigint generated by default as identity primary key,
  clinic_id bigint not null references public.clinics(id) on delete restrict,
  branch_id bigint references public.branches(id) on delete restrict,
  customer_id bigint not null references public.customers(id) on delete cascade,
  appointment_id bigint references public.appointments(id) on delete cascade,
  suggestion_type text not null check(suggestion_type in('confirmation','followup','aftercare','payment','retention','complaint')),
  title text not null,
  suggested_action text not null,
  priority text not null default 'medium' check(priority in('low','medium','high','urgent')),
  status text not null default 'open' check(status in('open','approved','dismissed','completed')),
  generated_by text not null default 'rules' check(generated_by in('rules','ai')),
  reviewed_by bigint references public.staff(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);
create unique index if not exists patient_open_suggestion_unique on public.patient_automation_suggestions(customer_id,appointment_id,suggestion_type) where status='open';

do $$ declare v_table text; begin
  foreach v_table in array array['patient_appointment_requests','patient_consents','patient_messages','patient_packages','patient_push_tokens','patient_automation_suggestions'] loop
