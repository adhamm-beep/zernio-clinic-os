begin;

create table if not exists public.patient_progress_media (
  id bigint generated by default as identity primary key,
  clinic_id bigint not null references public.clinics(id) on delete restrict,
  customer_id bigint not null references public.customers(id) on delete cascade,
  treatment_session_id bigint references public.treatment_sessions(id) on delete set null,
  media_type text not null check(media_type in('before','after','progress')),
  storage_path text not null unique,
  caption text,
  captured_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create index if not exists patient_progress_media_customer_idx on public.patient_progress_media(customer_id,captured_at desc);
alter table public.patient_progress_media enable row level security;
drop policy if exists patient_progress_media_self_read on public.patient_progress_media;
create policy patient_progress_media_self_read on public.patient_progress_media for select to authenticated
using(customer_id=public.current_patient_customer_id());

insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types)
values('patient-progress','patient-progress',false,10485760,array['image/jpeg','image/png','image/webp'])
on conflict(id) do update set public=false,file_size_limit=excluded.file_size_limit,allowed_mime_types=excluded.allowed_mime_types;

drop policy if exists patient_progress_storage_self_read on storage.objects;
create policy patient_progress_storage_self_read on storage.objects for select to authenticated
using(bucket_id='patient-progress' and exists(
  select 1 from public.patient_progress_media m
  where m.storage_path=storage.objects.name and m.customer_id=public.current_patient_customer_id()
));

create or replace function public.patient_results_hub()
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  v_customer_id bigint:=public.current_patient_customer_id();
  v_has_upcoming boolean;
  v_last_service text;
  v_followup boolean:=false;
begin
  if v_customer_id is null then raise exception 'Patient account is not linked'; end if;
  select exists(select 1 from appointments where customer_id=v_customer_id and appointment_at>=now() and lower(coalesce(status,'')) not in('cancelled','canceled')) into v_has_upcoming;
  select s.name,coalesce(ts.followup_required,false) into v_last_service,v_followup
  from treatment_sessions ts left join appointments a on a.id=ts.appointment_id left join services s on s.id=a.service_id
  where ts.customer_id=v_customer_id order by ts.session_date desc limit 1;

  return jsonb_build_object(
    'media',coalesce((select jsonb_agg(jsonb_build_object(
      'id',m.id,'type',m.media_type,'path',m.storage_path,'caption',m.caption,'capturedAt',m.captured_at,'sessionId',m.treatment_session_id
    ) order by m.captured_at desc) from patient_progress_media m where m.customer_id=v_customer_id),'[]'::jsonb),
    'recommendations',jsonb_build_array(
      jsonb_build_object('id','routine','icon','sparkles','title','Keep your care plan on track','message',case when v_last_service is null then 'Start with a consultation to create a plan tailored to you.' else 'Review your aftercare instructions for '||v_last_service||' and contact the clinic if you have questions.' end,'action',case when v_last_service is null then 'book' else 'care' end,'priority',1),
      jsonb_build_object('id','next-visit','icon','calendar','title',case when v_has_upcoming then 'Your next visit is arranged' else 'Plan your next visit' end,'message',case when v_has_upcoming then 'Open your journey to follow appointment progress.' else 'Choose a convenient time to continue your care journey.' end,'action',case when v_has_upcoming then 'appointments' else 'book' end,'priority',2),
      jsonb_build_object('id','followup','icon','chatbubble-ellipses','title','Care team support','message',case when v_followup then 'Your care plan includes a follow-up. Check your journey for the recommended date.' else 'Your Panthera care team is available whenever you need support.' end,'action','care','priority',3)
    )
  );
end;
$$;

revoke all on function public.patient_results_hub() from public;
grant execute on function public.patient_results_hub() to authenticated;
commit;

with checks as(
 select 'patient_progress_media_table' check_name,count(*)::bigint value,1::bigint expected from information_schema.tables where table_schema='public' and table_name='patient_progress_media'
 union all select 'patient_progress_private_bucket',count(*)::bigint,1::bigint from storage.buckets where id='patient-progress' and public=false
 union all select 'patient_progress_rls',count(*)::bigint,1::bigint from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname='public' and c.relname='patient_progress_media' and c.relrowsecurity
 union all select 'patient_results_function',count(*)::bigint,1::bigint from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public' and p.proname='patient_results_hub'
)
select case when value=expected then 'OK' else 'CHECK' end status,check_name,value,expected from checks order by check_name;
