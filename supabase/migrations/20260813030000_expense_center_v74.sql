  insert into public.accounting_journal_entries(clinic_id,branch_id,entry_number,entry_date,description_en,description_ar,status,source_type,source_id,posted_at)
  values(new.clinic_id,new.branch_id,'INC-'||new.id,new.income_date::date,'Manual income: '||new.name,'دخل مباشر: '||new.name,'posted','manual_income',new.id,now()) returning id into entry_id;
  insert into public.accounting_journal_lines(entry_id,clinic_id,account_id,staff_id,debit,credit,memo_en,memo_ar) values
  (entry_id,new.clinic_id,debit_id,new.assigned_to_staff_id,new.amount,0,coalesce(new.reference_number,new.payment_method),coalesce(new.reference_number,new.payment_method)),
  (entry_id,new.clinic_id,credit_id,new.assigned_to_staff_id,0,new.amount,new.name,new.name);
  return new;
end$$;
