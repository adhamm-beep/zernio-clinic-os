create or replace function public.validate_clinic_expense_payment() returns trigger language plpgsql security definer set search_path=public as $$
declare expense_total numeric; already_paid numeric;
begin
  select total_amount into expense_total from public.clinic_expenses where id=new.expense_id for update;
  if expense_total is null then raise exception 'Expense not found'; end if;
  select coalesce(sum(amount),0) into already_paid from public.clinic_expense_payments where expense_id=new.expense_id and id<>coalesce(new.id,0);
  if already_paid+new.amount>expense_total then raise exception 'Expense payment exceeds the outstanding amount'; end if;
  return new;
end$$;
drop trigger if exists validate_clinic_expense_payment_trigger on public.clinic_expense_payments;
create trigger validate_clinic_expense_payment_trigger before insert or update of expense_id,amount on public.clinic_expense_payments for each row execute function public.validate_clinic_expense_payment();

create or replace function public.refresh_clinic_expense_totals() returns trigger language plpgsql security definer set search_path=public as $$
declare target_id bigint; paid numeric;
begin
  target_id:=case when tg_op='DELETE' then old.expense_id else new.expense_id end;
  select coalesce(sum(amount),0) into paid from public.clinic_expense_payments where expense_id=target_id;
  update public.clinic_expenses set paid_amount=paid,status=case when status='cancelled' then status when paid<=0 then 'open' when paid>=total_amount then 'paid' else 'partial' end,updated_at=now() where id=target_id;
  return null;
end$$;
drop trigger if exists refresh_clinic_expense_totals_trigger on public.clinic_expense_payments;
create trigger refresh_clinic_expense_totals_trigger after insert or update or delete on public.clinic_expense_payments for each row execute function public.refresh_clinic_expense_totals();

create or replace function public.accounting_expense_payment_post() returns trigger language plpgsql security definer set search_path=public as $$
declare expense_row public.clinic_expenses%rowtype; entry_id bigint; debit_id bigint; credit_id bigint;
begin
  select * into expense_row from public.clinic_expenses where id=new.expense_id;
  delete from public.accounting_journal_entries where clinic_id=new.clinic_id and source_type='expense_payment' and source_id=new.id;
  debit_id:=public.accounting_account_id(new.clinic_id,expense_row.account_key);
  credit_id:=public.accounting_account_id(new.clinic_id,case when new.treasury_key in('bank','gateway_clearing','cash') then new.treasury_key else 'cash' end);
  insert into public.accounting_journal_entries(clinic_id,branch_id,entry_number,entry_date,description_en,description_ar,status,source_type,source_id,posted_at)
  values(new.clinic_id,new.branch_id,'EXP-'||new.id,new.payment_date::date,'Expense payment: '||expense_row.name,'دفعة مصروف: '||expense_row.name,'posted','expense_payment',new.id,now()) returning id into entry_id;
  insert into public.accounting_journal_lines(entry_id,clinic_id,account_id,staff_id,debit,credit,memo_en,memo_ar) values
  (entry_id,new.clinic_id,debit_id,expense_row.assigned_to_staff_id,new.amount,0,expense_row.name,expense_row.name),
  (entry_id,new.clinic_id,credit_id,expense_row.assigned_to_staff_id,0,new.amount,coalesce(new.reference_number,new.payment_method),coalesce(new.reference_number,new.payment_method));
  return new;
end$$;
drop trigger if exists accounting_expense_payment_trigger on public.clinic_expense_payments;
create trigger accounting_expense_payment_trigger after insert or update of amount,payment_method,treasury_key,payment_date,reference_number on public.clinic_expense_payments for each row execute function public.accounting_expense_payment_post();

create or replace function public.accounting_finance_source_cleanup() returns trigger language plpgsql security definer set search_path=public as $$
begin
  delete from public.accounting_journal_entries
  where clinic_id=old.clinic_id
    and source_type=case when tg_table_name='clinic_incomes' then 'manual_income' else 'expense_payment' end
    and source_id=old.id;
  return old;
end$$;
drop trigger if exists accounting_expense_payment_cleanup_trigger on public.clinic_expense_payments;
create trigger accounting_expense_payment_cleanup_trigger after delete on public.clinic_expense_payments for each row execute function public.accounting_finance_source_cleanup();

create or replace function public.accounting_manual_income_post() returns trigger language plpgsql security definer set search_path=public as $$
declare entry_id bigint; debit_id bigint; credit_id bigint;
begin
  delete from public.accounting_journal_entries where clinic_id=new.clinic_id and source_type='manual_income' and source_id=new.id;
